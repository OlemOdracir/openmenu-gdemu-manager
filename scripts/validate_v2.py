"""Run production regressions/DPI checks and regenerate their public evidence."""
import argparse,hashlib,json,os,subprocess,sys,xml.etree.ElementTree as ET
from datetime import datetime,timezone
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
DOC=ROOT/'docs/V2_VALIDATION.md'


def source_digest():
    paths=list((ROOT/'src').rglob('*.py'))+list((ROOT/'src').rglob('*.json'))+list((ROOT/'src').rglob('*.svg'))+list((ROOT/'tests').glob('test_v2*.py'))+[Path(__file__)]
    digest=hashlib.sha256()
    for path in sorted(paths):
        digest.update(path.relative_to(ROOT).as_posix().encode());digest.update(path.read_bytes().replace(b'\r\n',b'\n'))
    return digest.hexdigest()


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check-docs',action='store_true');args=parser.parse_args()
    digest=source_digest()
    if args.check_docs:
        if not DOC.is_file() or f'`{digest}`' not in DOC.read_text(encoding='utf-8'):
            print('V2 evidence is stale. Run python scripts/validate_v2.py.');return 1
        print('V2 documentation matches source.');return 0
    target=ROOT/'build/v2-validation';target.mkdir(parents=True,exist_ok=True)
    rows=[];success=True
    for scale in ('1','1.25','1.5'):
        environment=dict(os.environ,QT_QPA_PLATFORM='offscreen',QT_SCALE_FACTOR=scale,LOCALAPPDATA=str(target/'runtime'),USERPROFILE=str(target/'profile'))
        for name in ('OPENMENU_GDEMU_MANAGER_HOME','OPENMENU_GDEMU_MANAGER_DOCUMENTS'):environment.pop(name,None)
        xml=target/f'tests-{scale}.xml'
        tests=[] if scale=='1' else ['tests/test_v2_workflows.py']
        run=subprocess.run([sys.executable,'-m','pytest',*tests,'-q','--disable-warnings',f'--junitxml={xml}'],cwd=ROOT,env=environment)
        if not xml.exists():return run.returncode or 1
        suites=ET.parse(xml).getroot().findall('testsuite')
        counts={key:sum(int(s.get(key,0)) for s in suites) for key in ('tests','failures','errors','skipped')}
        passed=counts['tests']-counts['failures']-counts['errors']-counts['skipped']
        rows.append(f"| {scale} | {'Full suite' if scale=='1' else 'V2 UI flows'} | {passed} | {counts['skipped']} | {counts['failures']+counts['errors']} |")
        success=success and run.returncode==0
    lines=['# V2 generated validation','','Generated by `python scripts/validate_v2.py`. Do not edit results manually.','',f"UTC: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",'',f'Source digest: `{digest}`','',f"Result: **{'PASS' if success else 'FAIL'}**",'', '| Qt scale | Scope | Passed | Skipped | Failed |','| --- | --- | ---: | ---: | ---: |',*rows,'',
        'These checks use generated covers and synthetic discs. They do not contact online providers or write to a real SD. The skipped network tests remain unverified.',
        '', 'Portable startup is checked separately with `OpenMenuGDEMUManager.exe --self-test report.json`. It must report v2 startup/icons with no errors and without SD scanning or network requests.',
        '', '**Release gates still pending:** clean Windows VM; actual provider downloads; CDI internal descriptor/track-bound validation; Dreamcast/GDEMU launch of imported GDI/CDI games. Existing v1 hardware reports do not certify this v2 build.','']
    DOC.write_text('\n'.join(lines),encoding='utf-8')
    return 0 if success else 1


if __name__=='__main__':raise SystemExit(main())
